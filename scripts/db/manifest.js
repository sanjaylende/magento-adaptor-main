#!/usr/bin/env node
// db:manifest - the reference structure that db:verify compares a live database with (db/structure.manifest.json, committed).
//   npm run db:manifest                  prints the live structure's counts and whether it equals the committed manifest
//   npm run db:manifest -- --write       rewrites the manifest from the live schema (do this, and review the diff, when a migration changes the structure)
// Read-only on the database. Never prints credentials.
require("dotenv").config();
const fs = require("fs");
const path = require("path");
const config = require("../../src/config");
const { migrationPool, close } = require("../../src/db/connection");
const { migrationStatus } = require("../../src/db/migrate");
const { readStructure, diffStructure } = require("../../src/db/structure");

const FILE = path.join(__dirname, "..", "..", "db", "structure.manifest.json");

(async () => {
  const appRole = decodeURIComponent(new URL(config.database.url).username);
  const client = await migrationPool().connect();
  try {
    const status = await migrationStatus();
    if (status.pending.length) throw new Error("migrations are pending (" + status.pending.join(", ") + "): run npm run db:migrate first");
    const structure = await readStructure(client, config.database.schema, appRole);
    const counts = Object.entries(structure).map(([k, v]) => k + "=" + v.length).join(", ");
    if (process.argv.includes("--write")) {
      const manifest = { note: "Generated by npm run db:manifest -- --write from the reference schema; do not edit by hand.", migrations: status.files, structure };
      fs.mkdirSync(path.dirname(FILE), { recursive: true });
      fs.writeFileSync(FILE, JSON.stringify(manifest, null, 1) + "\n");
      console.log("wrote db/structure.manifest.json (" + counts + ")");
    } else {
      const current = fs.existsSync(FILE) ? JSON.parse(fs.readFileSync(FILE, "utf8")) : null;
      console.log("live structure: " + counts);
      if (!current) console.log("no manifest yet: npm run db:manifest -- --write");
      else {
        const drift = diffStructure(current.structure, structure);
        console.log(Object.keys(drift).length ? "DIFFERS from db/structure.manifest.json in: " + Object.keys(drift).join(", ") : "equals db/structure.manifest.json");
        process.exitCode = Object.keys(drift).length ? 1 : 0;
      }
    }
  } finally {
    client.release();
    await close();
  }
})().catch((err) => { console.error("db:manifest failed:", err.message); process.exit(2); });
